"""Router for Unified Hazards and Officer Action Approvals.

Rules:
  - Returns per-hazard results without any combined total risk score.
  - Exposes Tier A and Tier B modules.
  - All recommended actions require officer approval.
"""
from __future__ import annotations

from typing import Dict, List, Optional
from fastapi import APIRouter, Depends, HTTPException, Query, Request

from backend.auth.officer import get_optional_officer, require_officer
from backend.models import (
    HazardItem,
    HazardModuleStatus,
    RecommendedAction,
    UnifiedHazardResponse,
)
from backend.services.hazards.actions_store import (
    approve_action,
    get_action,
    list_actions,
    reject_action,
)
from backend.services.hazards.engine import unified_hazard_engine

router = APIRouter(prefix="/api/hazards", tags=["Unified Hazards"])


@router.get("", response_model=UnifiedHazardResponse)
async def get_all_hazards(
    min_lat: Optional[float] = Query(None, description="Bounding box minimum latitude"),
    max_lat: Optional[float] = Query(None, description="Bounding box maximum latitude"),
    min_lon: Optional[float] = Query(None, description="Bounding box minimum longitude"),
    max_lon: Optional[float] = Query(None, description="Bounding box maximum longitude"),
):
    """Retrieve per-hazard assessment features and statuses across all modules.

    Strict Contract: total_risk_score is ALWAYS null. No combined risk score is computed.
    """
    bbox = None
    if None not in (min_lat, max_lat, min_lon, max_lon):
        bbox = {
            "min_lat": min_lat,
            "max_lat": max_lat,
            "min_lon": min_lon,
            "max_lon": max_lon,
        }
    try:
        return await unified_hazard_engine.assess_all(bbox=bbox)
    except Exception as exc:
        raise HTTPException(status_code=500, detail=f"Failed to assess hazards: {exc}")


@router.get("/modules", response_model=Dict[str, HazardModuleStatus])
async def get_hazard_modules():
    """Retrieve operational status for all Tier A and Tier B hazard modules."""
    try:
        return await unified_hazard_engine.get_module_statuses()
    except Exception as exc:
        raise HTTPException(status_code=500, detail=f"Failed to retrieve hazard module statuses: {exc}")


@router.get("/actions", response_model=List[RecommendedAction])
async def get_recommended_actions(
    status: Optional[str] = Query(None, description="Filter by 'suggested', 'approved', 'rejected'"),
):
    """Retrieve response recommendations generated by hazard assessments.

    All recommendations require explicit officer approval before dispatch.
    """
    return list_actions(status=status)


@router.post("/actions/{action_id}/approve", response_model=RecommendedAction)
async def approve_response_action(
    action_id: str,
    request: Request,
):
    """Approve a suggested response action. Requires officer authentication if auth is enabled."""
    officer = get_optional_officer(request)
    officer_name = officer.username if officer else "Watch Officer"
    approved = approve_action(action_id, officer_name=officer_name)
    if not approved:
        raise HTTPException(status_code=404, detail=f"Action with ID {action_id} not found.")
    return approved


@router.post("/actions/{action_id}/reject", response_model=RecommendedAction)
async def reject_response_action(
    action_id: str,
    request: Request,
):
    """Reject a suggested response action. Requires officer authentication if auth is enabled."""
    officer = get_optional_officer(request)
    officer_name = officer.username if officer else "Watch Officer"
    rejected = reject_action(action_id, officer_name=officer_name)
    if not rejected:
        raise HTTPException(status_code=404, detail=f"Action with ID {action_id} not found.")
    return rejected
