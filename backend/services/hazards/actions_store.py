"""In-memory and persistent action store for response recommendations.

Response recommendations are generated by hazard modules as suggestions.
Every action requires explicit officer approval before dispatch or execution.
"""
from __future__ import annotations

import logging
from datetime import datetime, timezone
from typing import Dict, List, Optional
from backend.models import RecommendedAction

logger = logging.getLogger("vanta.hazards.actions")

_ACTIONS_STORE: Dict[str, RecommendedAction] = {}


def list_actions(status: Optional[str] = None) -> List[RecommendedAction]:
    """List recommended actions, optionally filtered by status ('suggested', 'approved', 'rejected')."""
    actions = list(_ACTIONS_STORE.values())
    if status:
        actions = [a for a in actions if a.status == status]
    return sorted(actions, key=lambda a: a.suggested_at, reverse=True)


def get_action(action_id: str) -> Optional[RecommendedAction]:
    return _ACTIONS_STORE.get(action_id)


def save_actions(actions: List[RecommendedAction]) -> None:
    """Store new actions if not already present."""
    for action in actions:
        if action.id not in _ACTIONS_STORE:
            _ACTIONS_STORE[action.id] = action


def approve_action(action_id: str, officer_name: str) -> Optional[RecommendedAction]:
    """Mark an action approved by an authenticated officer."""
    action = _ACTIONS_STORE.get(action_id)
    if not action:
        return None
    now_iso = datetime.now(timezone.utc).isoformat()
    updated = action.model_copy(update={
        "status": "approved",
        "approved_by": officer_name,
        "approved_at": now_iso,
    })
    _ACTIONS_STORE[action_id] = updated
    logger.info("Officer %r APPROVED hazard response action %s (%s)", officer_name, action_id, action.description)
    return updated


def reject_action(action_id: str, officer_name: str) -> Optional[RecommendedAction]:
    """Mark an action rejected by an authenticated officer."""
    action = _ACTIONS_STORE.get(action_id)
    if not action:
        return None
    now_iso = datetime.now(timezone.utc).isoformat()
    updated = action.model_copy(update={
        "status": "rejected",
        "approved_by": officer_name,
        "approved_at": now_iso,
    })
    _ACTIONS_STORE[action_id] = updated
    logger.info("Officer %r REJECTED hazard response action %s (%s)", officer_name, action_id, action.description)
    return updated
